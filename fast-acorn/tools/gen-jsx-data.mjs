// Generates fast-acorn/jsx-data.mjs from acorn-jsx 5.3.2 (node_modules):
// the exact source texts used to recognise the genuine plugin class, and
// its XHTML entity table.  node fast-acorn/tools/gen-jsx-data.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const require = createRequire(join(here, "../../package.json"));
const pkgPath = require.resolve("acorn-jsx/package.json");
const pkg = JSON.parse(readFileSync(pkgPath, "utf8"));
if (pkg.version !== "5.3.2") throw new Error("expected acorn-jsx 5.3.2, found " + pkg.version);
const acorn = require("acorn");
const jsx = require("acorn-jsx");
const C = acorn.Parser.extend(jsx());
const J = C.acornJsx;

const methods = {};
for (const name of Object.getOwnPropertyNames(C.prototype)) {
  if (name === "constructor") continue;
  methods[name] = Function.prototype.toString.call(C.prototype[name]);
}
const getter = Object.getOwnPropertyDescriptor(C, "acornJsx").get;
const indexSrc = readFileSync(join(dirname(pkgPath), "index.js"), "utf8");
const xhtmlSrc = readFileSync(join(dirname(pkgPath), "xhtml.js"), "utf8");
const classSrc = Function.prototype.toString.call(C);
if (!indexSrc.includes(classSrc)) throw new Error("class source not found verbatim");
const entities = require(join(dirname(pkgPath), "xhtml.js"));
const entityBody = xhtmlSrc.replace(/^module\.exports = /, "").replace(/;\s*$/, "");
// the table must be the same plain object literal (same keys, same order)
const check = new Function("return " + entityBody)();
if (JSON.stringify(check) !== JSON.stringify(entities)) throw new Error("entity table mismatch");

const out = `// Generated by tools/gen-jsx-data.mjs from acorn-jsx ${pkg.version} (MIT). Do not edit.
// Source texts of the genuine acorn-jsx plugin class, used to recognise it
// exactly, and acorn-jsx's XHTML entity table (xhtml.js).

export const JSX_VERSION = ${JSON.stringify(pkg.version)};
export const JSX_CLASS_SRC = ${JSON.stringify(classSrc)};
export const JSX_METHOD_SRC = ${JSON.stringify(methods, null, 1)};
export const JSX_GETTER_SRC = ${JSON.stringify(Function.prototype.toString.call(getter))};
export const JSX_TAGSTART_UC_SRC = ${JSON.stringify(Function.prototype.toString.call(J.tokTypes.jsxTagStart.updateContext))};
export const JSX_TAGEND_UC_SRC = ${JSON.stringify(Function.prototype.toString.call(J.tokTypes.jsxTagEnd.updateContext))};
export const JSX_PLUGIN_SRC = ${JSON.stringify(Function.prototype.toString.call(jsx))};

// acorn-jsx/xhtml.js (a plain object: lookups behave exactly like acorn-jsx's,
// including inherited properties such as "toString")
export const XHTMLEntities = ${entityBody};
`;
writeFileSync(join(here, "../jsx-data.mjs"), out);
console.log("wrote jsx-data.mjs", out.length, "bytes;", Object.keys(methods).length, "methods");

// fast-acorn/acorn-jsx.mjs: acorn-jsx as an ES module on fast-acorn's Parser,
// with the plugin class body byte-identical; classes it creates on
// fast-acorn's Parser are registered for the fast JSX path (by identity, so
// this also works after bundling/minification)
function replaceOnce(s, a, b) {
  if (s.split(a).length !== 2) throw new Error("pattern not found once: " + a);
  return s.replace(a, () => b);
}
let esm = indexSrc;
esm = replaceOnce(esm, "'use strict';\n\nconst XHTMLEntities = require('./xhtml');", `// Generated by tools/gen-jsx-data.mjs from acorn-jsx ${pkg.version} (MIT, Ingvar Stepanyan). Do not edit.
// Drop-in replacement for acorn-jsx: \`import acornJsx from "fast-acorn/acorn-jsx.mjs"\`.
import * as V from "./vendor/acorn.mjs";
import { XHTMLEntities } from "./jsx-data.mjs";
import { registerJsxClass } from "./jsx-detect.mjs";`);
esm = replaceOnce(
  esm,
  `module.exports = function(options) {
  options = options || {};
  return function(Parser) {
    return plugin({
      allowNamespaces: options.allowNamespaces !== false,
      allowNamespacedObjects: !!options.allowNamespacedObjects
    }, Parser);
  };
};`,
  `export default function acornJsx(options) {
  options = options || {};
  return function(Parser) {
    const pluginOptions = {
      allowNamespaces: options.allowNamespaces !== false,
      allowNamespacedObjects: !!options.allowNamespacedObjects
    };
    const cls = plugin(pluginOptions, Parser);
    if (Parser === V.Parser) registerJsxClass(cls, pluginOptions);
    return cls;
  };
}`,
);
esm = replaceOnce(esm, `Object.defineProperty(module.exports, "tokTypes", {
  get: function get_tokTypes() {
    return getJsxTokens(require("acorn")).tokTypes;
  },`, `Object.defineProperty(acornJsx, "tokTypes", {
  get: function get_tokTypes() {
    return getJsxTokens(V).tokTypes;
  },`);
esm = replaceOnce(esm, `const acorn = Parser.acorn || require("acorn");`, `const acorn = Parser.acorn || V;`);
if (!esm.includes(classSrc)) throw new Error("class body changed");
if (/require\(/.test(esm)) throw new Error("require left");
writeFileSync(join(here, "../acorn-jsx.mjs"), esm);
console.log("wrote acorn-jsx.mjs", esm.length, "bytes");
