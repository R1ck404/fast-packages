// Generates jsx-data.mts from acorn-jsx 5.3.2 (node_modules): what
// jsx-detect.mts needs to recognise the genuine plugin class exactly -- a
// hash and the length of the class's source text, the prototype's method
// names, hashes of the two token types' context hooks. (Not its XHTML entity
// table: the fast parser reads entities with the plugin's own jsx_readEntity.)
//   node packages/fast-acorn/tools/gen-jsx-data.mjs
// (then node tools/ts-build.mjs for jsx-data.mjs)
import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const require = createRequire(join(here, "../../../package.json"));
const pkgPath = require.resolve("acorn-jsx/package.json");
const pkg = JSON.parse(readFileSync(pkgPath, "utf8"));
if (pkg.version !== "5.3.2") throw new Error("expected acorn-jsx 5.3.2, found " + pkg.version);
const acorn = require("acorn");
const jsx = require("acorn-jsx");
const C = acorn.Parser.extend(jsx());
const J = C.acornJsx;
const src = (f) => Function.prototype.toString.call(f);

// the same hash as jsx-detect.mts (53-bit, cyrb53)
function hash(str) {
  let h1 = 0xdeadbeef, h2 = 0x41c6ce57;
  for (let i = 0; i < str.length; i++) {
    const ch = str.charCodeAt(i);
    h1 = Math.imul(h1 ^ ch, 2654435761);
    h2 = Math.imul(h2 ^ ch, 1597334677);
  }
  h1 = Math.imul(h1 ^ (h1 >>> 16), 2246822507) ^ Math.imul(h2 ^ (h2 >>> 13), 3266489909);
  h2 = Math.imul(h2 ^ (h2 >>> 16), 2246822507) ^ Math.imul(h1 ^ (h1 >>> 13), 3266489909);
  return 4294967296 * (2097151 & h2) + (h1 >>> 0);
}

const classSrc = src(C);
const indexSrc = readFileSync(join(dirname(pkgPath), "index.js"), "utf8");
if (!indexSrc.includes(classSrc)) throw new Error("class source not found verbatim");
const slice = (s) => {
  const i = classSrc.indexOf(s);
  if (i < 0 || classSrc.indexOf(s, i + 1) >= 0) throw new Error("method source not found exactly once in the class source:\n" + s);
  return [i, i + s.length];
};
// (each method's source occurs once in the class source and starts with its
// name: jsx-detect.mts checks both)
const methods = [];
for (const name of Object.getOwnPropertyNames(C.prototype)) {
  if (name === "constructor") continue;
  const s = src(C.prototype[name]);
  slice(s);
  if (!s.startsWith(name + "(")) throw new Error("method source does not start with its name: " + name);
  methods.push(name);
}
const getterSrc = src(Object.getOwnPropertyDescriptor(C, "acornJsx").get);
slice(getterSrc);
if (!getterSrc.startsWith("get acornJsx(")) throw new Error("getter source");

const out = `// Generated by tools/gen-jsx-data.mjs from acorn-jsx ${pkg.version} (MIT). Do not edit.
// What recognises the genuine acorn-jsx plugin class (see jsx-detect.mts).

// the class's source text: hash and length
export const JSX_CLASS = [${hash(classSrc)}, ${classSrc.length}];
// the prototype's methods (besides the constructor)
export const JSX_METHODS = ${JSON.stringify(methods.join(" "))};
// hashes of jsxTagStart's and jsxTagEnd's updateContext sources
export const JSX_UPDATE_CONTEXT = [${hash(src(J.tokTypes.jsxTagStart.updateContext))}, ${hash(src(J.tokTypes.jsxTagEnd.updateContext))}];
`;
writeFileSync(join(here, "../src/jsx-data.mts"), out);
console.log("wrote jsx-data.mts", out.length, "bytes;", methods.length, "methods");
